  /** 仅剧情节点解锁，不参与好感自动解锁 */
  storyUnlock?: boolean
  /** 剧情节点 id（可选，用于跳转回忆） */
  storyHint?: string
  /** 所属路线；有值时仅在该路线自动按好感解锁 */
