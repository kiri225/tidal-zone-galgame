let changed = 0
for (let n = 16; n <= 50; n++) {
  const file = path.join(dir, `ch${String(n).padStart(2, '0')}.ts`)
  if (!fs.existsSync(file)) continue
  let src = fs.readFileSync(file, 'utf8')
  const p = PATCH[n]
  if (!p) continue

  const pad = String(n).padStart(2, '0')

  // Replace r0/r1/r2 text fields if they match filler OR we have overrides
  for (const key of ['r0', 'r1', 'r2']) {
    if (!p[key]) continue
    const id = `c${pad}-${key}`
    const re = new RegExp(
      `(id: '${id}',[\\s\\S]*?text: ')([^']*)(')`,
      'm',
    )
    const m = src.match(re)
    if (!m) continue
    // Always apply unique text for r1/r2 when filler; for r0 apply if filler or we want override
    if (key === 'r0' && m[2] !== FILLER && !KEY_THICKEN[n]) {
      // keep existing unique r0 unless it's filler
      if (m[2] !== FILLER) {
        // still allow override for chapters where we wrote better r0
        if (n === 19 || n === 20 || n === 44 || n === 45) {
          src = src.replace(re, `$1${p[key].replace(/'/g, "\\'")}$3`)
          changed++
        }
        continue
      }
    }
    src = src.replace(re, `$1${p[key].replace(/'/g, "\\'")}$3`)
    changed++
  }

  if (p.end) {
    const reEnd = new RegExp(
      `(id: 'c${pad}-end',[\\s\\S]*?text: ')([^']*)(')`,
      'm',
    )
    if (reEnd.test(src)) {
      src = src.replace(reEnd, `$1${p.end.replace(/'/g, "\\'")}$3`)
      changed++
    }
  }

  // Global leftover filler cleanup inside this file
  if (src.includes(FILLER)) {
    // replace remaining fillers with r1 text or generic unique
    const fallback = p.r1 || p.r2 || p.r0 || '她把那一瞬间折进眼底，像一张不归档的废单。'
    src = src.split(FILLER).join(fallback)
    changed++
  }
  if (src.includes(END_FILLER)) {
    const fallback = p.end || '夜班的灯还亮着。有些潮位，要等下一章才退尽。'
    src = src.split(END_FILLER).join(fallback)
    changed++
  }

  // Comment header tweak
  src = src.replace('苏晴岚线 · 生成稿（可手改加厚）', '苏晴岚线 · 模板已清理')

  if (KEY_THICKEN[n]?.aftercg) {
    src = src.replace(
      /灯还亮着。有些画面已经发生，有些还差一个潮位。/g,
      KEY_THICKEN[n].aftercg,
    )
  }

  fs.writeFileSync(file, src)
  console.log('patched', path.basename(file))
}

